#!/usr/bin/env python3
"""ADR-053 D1：从 RTL 生成 rtovr_config.yaml 的 `allowed` 稀疏邻接表。

纪律（ADR-052 同款）：**禁止手抄常量，一律读源**。本脚本解析
`u280_sim_v422/smc/RtoVR/RtoVR.v` 的 `ifdef USE_RTOVR_SPARSE_MASK` 分支
（40 张 OUT_FROM_IN_EN_* 掩码，bit-i=1 ⟺ 允许输入 i 路由到该输出），
把结果幂等地拼接进 `hw_config/rtovr_config.yaml` 的
`rtovr_connectivity.allowed` 段（生成标记之间，禁止手改）。

用法：
    python3 verification_v2/tools/gen_rtovr_allowed.py [--check]

    默认      ：原地更新 hw_config/rtovr_config.yaml
    --check   ：只比对不落盘；漂移时 exit=1（守卫① 的 CI 形态）

注意：同一 repo 内 `tests/regression/` 的守卫① 应调用 `derive_allowed_from_rtl()`
直接比对 `hw_spec.get_rtovr_connectivity()`，保证 yaml 与 RTL 逐位一致。
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

COMPILER = Path(__file__).resolve().parents[2]
RTL_DEFAULT = Path.home() / "u280_sim_v422" / "smc" / "RtoVR" / "RtoVR.v"
YAML_PATH = COMPILER / "hw_config" / "rtovr_config.yaml"

BEGIN = "  # >>> GENERATED by verification_v2/tools/gen_rtovr_allowed.py — 源=RtoVR.v，禁止手改 <<<"
END = "  # >>> END GENERATED <<<"

# 结构语义分组注释（来自 ADR-053 §2，纯文档性，不参与比对）
GROUP_HINT = {
    **{i: "计算单元 S 口（禁 UR 30-33/禁 ST 2,5/禁 VOUT0_D 13）" for i in range(0, 13)},
    13: "LOGIC_ST 走档汇聚",
    14: "VIN0_S：UR 数据唯一入口", 15: "VIN1_S：UR 数据唯一入口",
    16: "VOUT0_S：计算结果唯一汇聚",
    17: "INT8 MAC 串链", 18: "INT8 MAC 串链",
    **{i: "INT8 MAC 串链" for i in range(19, 23)},
    23: "FP16MUL_S4567：广播移位馈乘加",
    **{i: "INT8 MAC 串链" for i in range(24, 32)},
    32: "INT8 MAC 串链", 33: "INT8 MAC 串链",
    34: "SHIFTDN_S：结果收集",
    35: "UR_WRITE_0_D：回写 UR 唯一通路", 36: "UR_WRITE_1_D：回写 UR 唯一通路",
    37: "UR_WRITE_2_D：回写 UR 唯一通路", 38: "UR_WRITE_3_D：回写 UR 唯一通路",
    39: "RESERVED：空",
}


def derive_allowed_from_rtl(rtl_path: Path = RTL_DEFAULT) -> dict[int, tuple[int, ...]]:
    """解析 RtoVR.v 稀疏掩码 → {out_idx: 升序输入索引元组}。唯一权威源。"""
    txt = rtl_path.read_text(encoding="utf-8", errors="replace")
    start = txt.index("`ifdef USE_RTOVR_SPARSE_MASK")
    end = txt.index("`else", start)
    seg = txt[start:end]
    masks: dict[int, int] = {}
    for m in re.finditer(r"OUT_FROM_IN_EN_(\d+)\s*=\s*64'h([0-9A-Fa-f_]+)\s*;", seg):
        masks[int(m.group(1))] = int(m.group(2).replace("_", ""), 16)
    if len(masks) != 40:
        raise RuntimeError(f"掩码表应有 40 项，实得 {len(masks)}（{rtl_path}）")
    return {
        out: tuple(i for i in range(64) if (mask >> i) & 1)
        for out, mask in sorted(masks.items())
    }


def render_block(allowed: dict[int, tuple[int, ...]], names: dict[int, str]) -> list[str]:
    """渲染 allowed 段的 yaml 行（含 BEGIN/END 标记）。names = out_idx→单元名（注释用）。"""
    lines = [BEGIN, "  allowed:"]
    for out, sels in allowed.items():
        name = names.get(out, f"OUT{out}")
        hint = GROUP_HINT.get(out, "")
        sel_txt = ", ".join(str(s) for s in sels)
        comment = f"  # {name}" + (f"（{hint}）" if hint else "")
        lines.append(f"    {out}: [{sel_txt}]{comment}")
    lines.append(END)
    return lines


def load_existing_out_names(yaml_text: str) -> dict[int, str]:
    """从 yaml 文本里抠 producers_dvr 的 out_idx→名字（仅作注释，权威是编号）。"""
    names: dict[int, str] = {}
    m = re.search(r"^  producers_dvr:\n((?:    .*\n)+)", yaml_text, re.MULTILINE)
    if m:
        for line in m.group(1).splitlines():
            kv = re.match(r"\s*(\d+):\s*(\S+)", line)
            if kv:
                names[int(kv.group(1))] = kv.group(2)
    return names


def splice(yaml_text: str, block: list[str]) -> str:
    """幂等拼接：有标记则替换标记区间，否则追加到文件尾。"""
    lines = yaml_text.splitlines()
    try:
        b = lines.index(BEGIN)
        e = lines.index(END)
        assert b < e
        lines = lines[:b] + block + lines[e + 1:]
    except ValueError:
        if lines and lines[-1].strip():
            lines.append("")
        lines.extend(block)
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只比对不落盘，漂移 exit=1")
    ap.add_argument("--rtl", type=Path, default=RTL_DEFAULT)
    args = ap.parse_args()

    allowed = derive_allowed_from_rtl(args.rtl)
    old_text = YAML_PATH.read_text(encoding="utf-8")
    names = load_existing_out_names(old_text)
    new_text = splice(old_text, render_block(allowed, names))

    if args.check:
        if new_text == old_text:
            print(f"[gen_rtovr_allowed] OK：{YAML_PATH} 与 {args.rtl} 逐位一致")
            return 0
        print(f"[gen_rtovr_allowed] DRIFT：{YAML_PATH} 与 RTL 不一致，"
              f"请运行 python3 {Path(__file__).relative_to(COMPILER)} 重新生成")
        return 1

    if new_text != old_text:
        YAML_PATH.write_text(new_text, encoding="utf-8")
        print(f"[gen_rtovr_allowed] 已更新 {YAML_PATH}（40 项 allowed 自 {args.rtl}）")
    else:
        print("[gen_rtovr_allowed] 无漂移，未改动")
    return 0


if __name__ == "__main__":
    sys.exit(main())
